// Bakes every puzzle from EPOCH to three years from now into src/days.js, using the site's own generator
// (site/js/daily.js). Building a day cold takes tens of milliseconds of CPU, more than the Workers free plan allows
// per request, so the worker looks days up here instead and builds one live only outside this range.
// wrangler runs this before every `deploy` and `dev` ([build] in wrangler.toml), so it can't go stale.
import fs from 'node:fs';
import { EPOCH, addDays, puzzle, todayKey } from '../site/js/daily.js';

const to = addDays(todayKey(), 3 * 366);
const days = {};
for (let d = EPOCH; d <= to; d = addDays(d, 1)) {
  const p = puzzle(d);
  // board words, then each group (easiest first) as positions on the board
  days[d] = [p.board.join(','), p.groups.map((g) => g.words.map((w) => p.board.indexOf(w).toString(36)).join(''))];
}
fs.writeFileSync(new URL('./src/days.js', import.meta.url),
  `// Generated by build-days.mjs from site/js/daily.js. Don't edit; it's rebuilt on every deploy.\nexport default ${JSON.stringify(days)};\n`);
console.log(`Baked ${Object.keys(days).length} days, ${EPOCH} to ${to}.`);
